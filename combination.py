def filter_items_by_style(user_style, categorized_data, style_items):
    # 결과를 저장할 딕셔너리
    filtered_data = {}

    # 스타일별 유효 카테고리를 가져옵니다.
    if user_style not in style_items:
        raise ValueError(f"Invalid style '{user_style}'. Please choose a valid style.")

    # 스타일별 카테고리 매핑
    style_categories = style_items[user_style]

    # 스타일 카테고리를 순회하며 데이터 필터링
    for category_type, valid_categories in style_categories.items():
        if category_type not in filtered_data:
            filtered_data[category_type] = []  # 초기화

        # categorized_data에서 해당 카테고리를 찾음
        db_category_key = None
        if category_type == "상의":
            db_category_key = "top"
        elif category_type == "바지":
            db_category_key = "pants"
        elif category_type == "치마":
            db_category_key = "skirt"
        elif category_type == "원피스":
            db_category_key = "dress"
        elif category_type == "아우터":
            db_category_key = "outer"

        if db_category_key and db_category_key in categorized_data:
            # 해당 데이터베이스 카테고리에서 유효한 카테고리를 필터링
            for valid_category in valid_categories:
                if valid_category in categorized_data[db_category_key]:
                    filtered_data[category_type].extend(
                        categorized_data[db_category_key][valid_category]
                    )

    return filtered_data


