def fetch_items_from_collections(db, collections, categories):
    all_data = {}

    for collection_name, category_list in collections.items():
        collection = db[collection_name]
        all_data[collection_name] = {}

        for category in category_list:
            # Aggregation Pipeline
            pipeline = [
                {"$match": {"category": category}},  # 카테고리 필터링
                {"$project": {"_id":0, "imageUrl": 1, "category": 1}},  # 필요한 필드만 포함
                {"$limit": 2} # 최대 3개 제한
            ]

            # Aggregation 실행
            results = collection.aggregate(pipeline)
            all_data[collection_name][category] = list(results)  # 결과를 리스트로 변환

    return all_data

